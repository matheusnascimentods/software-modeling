-- Fábrica de Móveis Madeira Verde — DDL
-- Cria o banco e as 18 tabelas do modelo (MariaDB / MySQL).

CREATE DATABASE MadeiraVerde;
USE MadeiraVerde;

CREATE TABLE ENDERECO (
    END_INT_ID INT NOT NULL AUTO_INCREMENT,
    END_STR_CEP CHAR(8),
    END_STR_NUMERO VARCHAR(8),
    END_STR_COMPLEMENTO VARCHAR(25),
    PRIMARY KEY (END_INT_ID)
);

CREATE TABLE EMPRESA (
    EMP_INT_ID INT NOT NULL AUTO_INCREMENT,
    ENDERECO_END_INT_ID INT NOT NULL,
    EMP_STR_CNPJ CHAR(14) NOT NULL UNIQUE,
    EMP_STR_PESSOA_CONTATO VARCHAR(20),
    EMP_STR_RAZAO_SOCIAL VARCHAR(25),
    EMP_STR_TELEFONE VARCHAR(15),
    PRIMARY KEY (EMP_INT_ID),
    FOREIGN KEY (ENDERECO_END_INT_ID) REFERENCES ENDERECO(END_INT_ID)
);

CREATE TABLE COMPONENTE (
    COM_INT_ID INT NOT NULL AUTO_INCREMENT,
    COM_STR_CODIGO_BARRA CHAR(14) NOT NULL UNIQUE,
    COM_STR_NOME VARCHAR(30) NOT NULL,
    COM_INT_QUANTIDADE_ESTOQUE INT NOT NULL,
    COM_FLO_PRECO_UNITARIO FLOAT NOT NULL,
    COM_STR_UNIDADE_ESTOQUE VARCHAR(35) NOT NULL,
    PRIMARY KEY (COM_INT_ID)
);

CREATE TABLE FERRAMENTA (
    FER_INT_ID INT NOT NULL AUTO_INCREMENT,
    COMPONENTE_COM_INT_ID INT NOT NULL,
    FER_DAT_DATA_COMPRA DATE NOT NULL,
    FER_INT_VIDA_UTIL INT NOT NULL,
    PRIMARY KEY (FER_INT_ID),
    FOREIGN KEY (COMPONENTE_COM_INT_ID) REFERENCES COMPONENTE(COM_INT_ID)
);

CREATE TABLE MATERIAL (
    MAT_INT_ID INT NOT NULL AUTO_INCREMENT,
    COMPONENTE_COM_INT_ID INT NOT NULL,
    MAT_STR_TIPO_MATERIAL VARCHAR(40) NOT NULL,
    MAT_INT_QUANTIDADE_NECESSARIA INT NOT NULL,
    MAT_STR_UNIDADE_MEDIDA VARCHAR(15) NOT NULL,
    PRIMARY KEY (MAT_INT_ID),
    FOREIGN KEY (COMPONENTE_COM_INT_ID) REFERENCES COMPONENTE(COM_INT_ID)
);

CREATE TABLE MAQUINA (
    MAQ_INT_ID INT NOT NULL AUTO_INCREMENT,
    COMPONENTE_COM_INT_ID INT NOT NULL,
    MAQ_INT_TEMPO_VIDA INT NOT NULL,
    MAQ_DAT_DATA_COMPRA DATE NOT NULL,
    MAQ_DAT_FIM_GARANTIA DATE NOT NULL,
    MAQ_STR_TEMPO_USO INT NOT NULL,
    PRIMARY KEY (MAQ_INT_ID),
    FOREIGN KEY (COMPONENTE_COM_INT_ID) REFERENCES COMPONENTE(COM_INT_ID)
);

CREATE TABLE FORNECEDOR (
    FOR_INT_ID INT NOT NULL AUTO_INCREMENT,
    EMPRESA_EMP_INT_ID INT NOT NULL,
    FOR_STR_EMAIL VARCHAR(45),
    PRIMARY KEY (FOR_INT_ID),
    FOREIGN KEY (EMPRESA_EMP_INT_ID) REFERENCES EMPRESA(EMP_INT_ID)
);

CREATE TABLE FORNECIDO (
    FOR_INT_ID INT NOT NULL AUTO_INCREMENT,
    COMPONENTE_COM_INT_ID INT NOT NULL,
    FORNECEDOR_FOR_INT_ID INT NOT NULL,
    FOR_INT_DEMANDA INT NOT NULL,
    PRIMARY KEY (FOR_INT_ID),
    FOREIGN KEY (COMPONENTE_COM_INT_ID) REFERENCES COMPONENTE(COM_INT_ID),
    FOREIGN KEY (FORNECEDOR_FOR_INT_ID) REFERENCES FORNECEDOR(FOR_INT_ID)
);

CREATE TABLE CLIENTE (
    CLI_INT_ID INT NOT NULL AUTO_INCREMENT,
    EMPRESA_EMP_INT_ID INT NOT NULL,
    ENDERECO_END_INT_ID INT NOT NULL,
    CLI_STR_ENDERECO_CORRESPONDENCIA VARCHAR(40),
    CLI_STR_RAMO_ATIVIDADE VARCHAR(20),
    CLI_DAT_DATA_CADASTRAMENTO DATE,
    CLI_STR_EMAIL VARCHAR(40),
    PRIMARY KEY (CLI_INT_ID),
    FOREIGN KEY (EMPRESA_EMP_INT_ID) REFERENCES EMPRESA(EMP_INT_ID),
    FOREIGN KEY (ENDERECO_END_INT_ID) REFERENCES ENDERECO(END_INT_ID)
);

CREATE TABLE FUNCIONARIO (
    FUN_INT_ID INT NOT NULL AUTO_INCREMENT,
    ENDERECO_END_INT_ID INT NOT NULL,
    FUNCIONARIO_FUN_INT_ID INT NOT NULL,
    FUN_STR_CPF CHAR(11),
    FUN_STR_MATRICULA VARCHAR(12),
    FUN_STR_NOME VARCHAR(35) NOT NULL,
    FUN_STR_TELEFONE VARCHAR(15) NOT NULL,
    FUN_STR_CARGO VARCHAR(35),
    FUN_FLO_SALARIO FLOAT NOT NULL,
    FUN_DAT_DATA_ADMISSAO DATE NOT NULL,
    FUN_STR_DESC_PROFISSIONAL VARCHAR(100),
    PRIMARY KEY (FUN_INT_ID),
    FOREIGN KEY (ENDERECO_END_INT_ID) REFERENCES ENDERECO(END_INT_ID),
    FOREIGN KEY (FUNCIONARIO_FUN_INT_ID) REFERENCES FUNCIONARIO(FUN_INT_ID)
);

CREATE TABLE PRODUTO (
    PRO_INT_ID INT NOT NULL AUTO_INCREMENT,
    PRO_STR_NOME VARCHAR(25) NOT NULL,
    PRO_STR_COR VARCHAR(25) NOT NULL,
    PRO_FLO_PESO FLOAT NOT NULL,
    PRO_FLO_PRECO FLOAT NOT NULL,
    PRO_STR_DESENHO_PRODUTO VARCHAR(70),
    PRO_FLO_LARGURA FLOAT NOT NULL,
    PRO_FLO_PROFUNDIDADE FLOAT NOT NULL,
    PRO_FLO_ALTURA FLOAT NOT NULL,
    PRO_INT_TEMPO_MEDIO_PRODUCAO INT NOT NULL,
    PRIMARY KEY (PRO_INT_ID)
);

CREATE TABLE COMPOSICAO_PRODUTO (
    COP_INT_ID INT NOT NULL AUTO_INCREMENT,
    PRODUTO_PRO_INT_ID INT NOT NULL,
    COMPONENTE_COM_INT_ID INT NOT NULL,
    COP_INT_QUATIDADE INT NOT NULL,
    PRIMARY KEY (COP_INT_ID),
    FOREIGN KEY (PRODUTO_PRO_INT_ID) REFERENCES PRODUTO(PRO_INT_ID),
    FOREIGN KEY (COMPONENTE_COM_INT_ID) REFERENCES COMPONENTE(COM_INT_ID)
);

CREATE TABLE MAO_OBRA (
    MAO_INT_ID INT NOT NULL AUTO_INCREMENT,
    FUNCIONARIO_FUN_INT_ID INT NOT NULL,
    PRODUTO_PRO_INT_ID INT NOT NULL,
    MAO_STR_DOCUMENTACAO VARCHAR(100),
    PRIMARY KEY (MAO_INT_ID),
    FOREIGN KEY (FUNCIONARIO_FUN_INT_ID) REFERENCES FUNCIONARIO(FUN_INT_ID),
    FOREIGN KEY (PRODUTO_PRO_INT_ID) REFERENCES PRODUTO(PRO_INT_ID)
);

CREATE TABLE ENCOMENDA (
    ENC_INT_ID INT NOT NULL AUTO_INCREMENT,
    ENDERECO_END_INT_ID INT NOT NULL,
    CLIENTE_CLI_INT_ID INT NOT NULL,
    ENC_INT_NUMERO_NF INT NOT NULL,
    ENC_DATA_INCLUSAO DATE,
    ENC_DOU_VALOR_TOTAL_ENC DOUBLE NOT NULL,
    ENC_DOU_DESCONTO DOUBLE,
    ENC_DOU_VALOR_LIQUIDO DOUBLE,
    ENC_DAT_DATA_NECESSIDADE DATE,
    ENC_ENU_FORMA_PAGAMENTO ENUM('Pix','Cartão de crédito','Cartão de débito','Boleto','Cheque'),
    ENC_QUANTIDADE_PARCELA INT,
    ENC_STR_NF VARCHAR(70),
    PRIMARY KEY (ENC_INT_ID),
    FOREIGN KEY (ENDERECO_END_INT_ID) REFERENCES ENDERECO(END_INT_ID),
    FOREIGN KEY (CLIENTE_CLI_INT_ID) REFERENCES CLIENTE(CLI_INT_ID)
);

CREATE TABLE ITEM_ENCOMENDA (
    ITE_INT_ID INT NOT NULL AUTO_INCREMENT,
    PRODUTO_PRO_INT_ID INT NOT NULL,
    ENCOMENDA_ENC_INT_ID INT NOT NULL,
    ITE_DAT_INICIO_PRODUCAO DATE,
    ITE_DAT_FIM_PRODUCAO DATE,
    ITE_INT_QUANTIDADE_PRODUTO INT NOT NULL,
    PRIMARY KEY (ITE_INT_ID),
    FOREIGN KEY (PRODUTO_PRO_INT_ID) REFERENCES PRODUTO(PRO_INT_ID),
    FOREIGN KEY (ENCOMENDA_ENC_INT_ID) REFERENCES ENCOMENDA(ENC_INT_ID)
);

CREATE TABLE MANUTENCAO (
    MAN_INT_ID INT NOT NULL AUTO_INCREMENT,
    EMPRESA_EMP_INT_ID INT NOT NULL,
    MAN_TIM_INICIO_EXPEDIENTE TIME NOT NULL,
    MAN_TIM_FIM_EXPEDIENTE TIME NOT NULL,
    PRIMARY KEY (MAN_INT_ID),
    FOREIGN KEY (EMPRESA_EMP_INT_ID) REFERENCES EMPRESA(EMP_INT_ID)
);

CREATE TABLE CERTIFICADO (
    CER_INT_ID INT NOT NULL AUTO_INCREMENT,
    MANUTENCAO_MAN_INT_ID INT NOT NULL,
    CER_STR_CERTIFICADO_PROFISSIONAL VARCHAR(50),
    PRIMARY KEY (CER_INT_ID),
    FOREIGN KEY (MANUTENCAO_MAN_INT_ID) REFERENCES MANUTENCAO(MAN_INT_ID)
);

CREATE TABLE ORDEM_SERVICO (
    ORD_INT_ID INT NOT NULL AUTO_INCREMENT,
    MANUTENCAO_MAN_INT_ID INT NOT NULL,
    MAQUINA_MAQ_INT_ID INT NOT NULL,
    ORD_DAT_DATA_MANUTENCAO DATE,
    ORD_STR_DESCRICAO_SERVICO VARCHAR(100),
    PRIMARY KEY (ORD_INT_ID),
    FOREIGN KEY (MANUTENCAO_MAN_INT_ID) REFERENCES MANUTENCAO(MAN_INT_ID),
    FOREIGN KEY (MAQUINA_MAQ_INT_ID) REFERENCES MAQUINA(MAQ_INT_ID)
);
